param(
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

# release/versions.json is the single source for the release number, the shared
# ordinary-contract number and the Android version code. Generated constants are
# committed so the Go and Java builds never depend on running this script first;
# every build entry point re-runs it (or -Check) before compiling.
$repository = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
$versionsPath = Join-Path $repository 'release/versions.json'
$goPath = Join-Path $repository 'internal/protocol/version_generated.go'
$javaPath = Join-Path $repository 'android-control/app/src/main/java/com/mobileuse/vnext/GeneratedVersion.java'
$stringsPath = Join-Path $repository 'android-control/app/src/main/res/values/strings_version.xml'
$manifestPath = Join-Path $repository 'android-control/app/src/main/AndroidManifest.xml'

if (-not (Test-Path -LiteralPath $versionsPath -PathType Leaf)) {
    throw "Version source is missing: $versionsPath"
}

$versions = Get-Content -LiteralPath $versionsPath -Raw | ConvertFrom-Json
$releaseVersion = [string]$versions.release_version
$contractVersion = [string]$versions.contract_version
$androidVersionCode = [string]$versions.android_version_code
$sourceCommit = [string]$versions.source_commit

if ($releaseVersion -notmatch '^\d+\.\d+\.\d+$') {
    throw "release_version must be MAJOR.MINOR.PATCH: $releaseVersion"
}
if ($contractVersion -notmatch '^[1-9][0-9]{0,2}$') {
    throw "contract_version must be a positive integer: $contractVersion"
}
if ($androidVersionCode -notmatch '^[1-9][0-9]{0,8}$') {
    throw "android_version_code must be a positive integer: $androidVersionCode"
}
if ($sourceCommit -notmatch '^[0-9a-fA-F]{7,40}$') {
    throw "source_commit must be a git commit prefix: $sourceCommit"
}

$goContent = @"
// Code generated by scripts/generate-version.ps1 from release/versions.json; DO NOT EDIT.

package protocol

// ContractVersion is the single ordinary-contract version shared by the device
// service, the SDK/MCP and the paired control App. Ordinary work requires exact
// equality; the minimal STOP carrier does not use it.
const ContractVersion = "$contractVersion"

// ReleaseVersion identifies this build artifact. It is not a contract and does
// not take part in capability negotiation.
var ReleaseVersion = "$releaseVersion"
"@

$javaContent = @"
// Code generated by scripts/generate-version.ps1 from release/versions.json; DO NOT EDIT.

package com.mobileuse.vnext;

/** 构建期单一版本源生成；不得手改。 */
final class GeneratedVersion {
    static final String RELEASE_VERSION = "$releaseVersion";
    static final String CONTRACT_VERSION = "$contractVersion";
    static final int ANDROID_VERSION_CODE = $androidVersionCode;
    private GeneratedVersion() {}
}
"@

$stringsContent = @"
<?xml version="1.0" encoding="utf-8"?>
<resources>
    <string name="app_version">$releaseVersion</string>
</resources>
"@

$manifestContent = [System.IO.File]::ReadAllText($manifestPath)
if ($manifestContent -notmatch 'android:versionCode="\d+"') {
    throw "AndroidManifest.xml has no android:versionCode attribute"
}
$expectedManifest = $manifestContent -replace 'android:versionCode="\d+"', "android:versionCode=`"$androidVersionCode`""

function Normalize-Newlines {
    param([string]$Text)
    return ($Text -replace "`r`n", "`n").TrimEnd("`n")
}

$targets = @(
    @{ Path = $goPath; Content = $goContent },
    @{ Path = $javaPath; Content = $javaContent },
    @{ Path = $stringsPath; Content = $stringsContent },
    @{ Path = $manifestPath; Content = $expectedManifest }
)

$failures = @()
foreach ($target in $targets) {
    $actual = if (Test-Path -LiteralPath $target.Path -PathType Leaf) {
        [System.IO.File]::ReadAllText($target.Path)
    } else {
        $null
    }
    if ($null -eq $actual -or (Normalize-Newlines $actual) -ne (Normalize-Newlines $target.Content)) {
        if ($Check) {
            $failures += $target.Path
        } else {
            $directory = Split-Path -Parent $target.Path
            New-Item -ItemType Directory -Path $directory -Force | Out-Null
            $encoding = New-Object System.Text.UTF8Encoding($false)
            [System.IO.File]::WriteAllText($target.Path, ($target.Content.TrimEnd("`n") + "`n"), $encoding)
        }
    }
}

if ($Check) {
    if ($failures.Count -gt 0) {
        Write-Output 'Generated version files are stale:'
        foreach ($failure in $failures) { Write-Output "  $failure" }
        exit 1
    }
    Write-Output "version source consistent: release=$releaseVersion contract=$contractVersion android_version_code=$androidVersionCode"
    exit 0
}

Write-Output "generated: release=$releaseVersion contract=$contractVersion android_version_code=$androidVersionCode source_commit=$sourceCommit"
